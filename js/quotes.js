export function getQuoteForDate(dateKey) {
  if (!QUOTES.length) {
    return {
      text: "从一个小动作开始，今天也会有所不同。",
      author: "微习惯",
      source: "",
    };
  }

  const index = ((dateKeyToSerial(dateKey) % QUOTES.length) + QUOTES.length) % QUOTES.length;
  return QUOTES[index];
}
